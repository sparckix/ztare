#!/usr/bin/env python3
"""Algebraic normal-two connection for the pure contact-zero parity tail.

The pure contact-zero quotient has one representative in every cusp weight:
``P**c`` in even weight and ``P**a*Q`` in odd weight.  After slope-two
rescaling, radial normalization is therefore a rank-two module over
``QQ[[y]]`` with ``y=x**2*Pcrit(x, 0)``.  This replay performs that
decomposition in the exact quadratic function field generated by the local
deck involution and extracts the complete normal-two instantaneous
connection.  It deliberately stops before inferring a logarithmic tail from
an instantaneous branch point.
"""


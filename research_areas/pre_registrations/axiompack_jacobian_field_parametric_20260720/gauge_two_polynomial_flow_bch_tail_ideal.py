#!/usr/bin/env python3
"""Oriented BCH tail ideals for two polynomial autonomous flows.

For endpoint maps ``F = Q o P``, substitution pullbacks compose as
``T_F = T_P * T_Q``.  If ``h = log(T_F)`` and ``p`` is the inner vector
field, the forced outer generator in the derivation convention is therefore

    q = BCH(-p, h).

An outer degree cap ``e`` is equivalent to vanishing of the coefficients of
``q`` above degree ``e``.  For an inner cap ``d``, the first overdetermined
tail ideal is generated by degrees ``e+1`` through ``e+d``.  This replay
constructs those ideals with the shared typed BCH kernel, checks their
orientation against direct time-one-map composition, and searches the fixed
inner-cubic lane for a resultant recurrence.

Finite resultant rows do not prove the all-degree cubic or two-flow claims.
"""


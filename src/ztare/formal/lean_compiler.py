"""ZTARE → Lean 4 Proof Stub Compiler.

Reads ZTARE gate results (gate_harness output, fit_result, iteration telemetry)
and generates Lean 4 proof stubs:
- Gate passes → existence witnesses (∃ params, ∀ grid points, bound holds)
- Gate failures → exclusion lemmas (∃ grid point where bound violated)
- Exponent grid selections → constraint narrowing lemmas (BIC ordering)
- Topology class exhaustion → search space pruning lemmas

ZTARE is the hypothesis generator. Lean is the proof engine.
This compiler is the bridge.

Usage:
    python -m src.ztare.formal.lean_compiler --project gp088_calibration_a01
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

from src.ztare.common.paths import PROJECTS_DIR


# ---------------------------------------------------------------------------
# Evidence loader
# ---------------------------------------------------------------------------

def load_evidence(path: Path) -> list[tuple[float, float]]:
    pts = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) >= 2:
            try:
                pts.append((float(parts[0]), float(parts[1])))
            except ValueError:
                continue
    return pts


# ---------------------------------------------------------------------------
# Lean 4 code generation
# ---------------------------------------------------------------------------

def emit_preamble(project: str, strict: bool = False) -> str:
    """Emit the Lean file preamble.

    GP-135 (2026-04-23) — strict hardening per external Lean panel review:
      - `warningAsError true` → any `sorry` in the stub becomes a hard
        compile error. Non-strict mode keeps `sorry` as a proof
        obligation marker (design of the current compiler).
      - The preamble documents the axiom allowlist the gate enforces
        post-compile: only {propext, Classical.choice, Quot.sound} are
        permitted; any user-declared axiom or `Classical.skipThe`
        fails the gate (enforced by scripts/verify_lean_stub.py).
      - Schema-pinned theorem headers: the compiler writes the
        `theorem NAME : STATEMENT := by …` header; candidate-supplied
        content can only live inside the `by …` block. This prevents
        statement dilution (e.g., substituting trivial statements).

    Non-strict mode is the default (existing behavior preserved for
    back-compat with Phase-3 documentation output). Strict mode is
    opt-in via `--strict` CLI flag and is the P4 primitive candidate.
    """
    warning_option = (
        "set_option warningAsError true  -- GP-135 strict: sorry becomes error\n"
        if strict else ""
    )
    strict_banner = (
        "\n  STRICT MODE (P4 gate): warningAsError is on; unclosed `sorry`\n"
        "  goals compile-fail. Post-compile, `scripts/verify_lean_stub.py`\n"
        "  enforces the axiom allowlist {propext, Classical.choice, Quot.sound}\n"
        "  and the schema-pinned theorem headers.\n"
        if strict else ""
    )
    return f"""\
/-
  ZTARE → Lean 4 Proof Stubs
  Project: {project}
  Generated by src/ztare/formal/lean_compiler.py
{strict_banner}
  These stubs encode the ZTARE gate harness results as Lean 4 proof
  obligations. In non-strict mode, each `sorry` is a proof goal to be
  discharged by native_decide, norm_num, or tactic automation. In
  strict mode, `sorry` is a compile error and every theorem must be
  closed before the gate passes.
-/

import Mathlib.Analysis.SpecialFunctions.Log.Basic
import Mathlib.Analysis.SpecialFunctions.Pow.Real
import Mathlib.Data.Fin.Basic

{warning_option}open Real

"""


def emit_evidence_def(name: str, pts: list[tuple[float, float]]) -> str:
    entries = ",\n    ".join(f"({n}, {v})" for n, v in pts)
    return f"""\
/-- Evidence grid: {name} --/
def {name} : List (Float × Float) :=
  [ {entries} ]

"""


def emit_gate_pass_witness(
    gate_name: str,
    threshold: float,
    expression: str,
    params: dict[str, float],
    grid_name: str,
    max_residual: float,
) -> str:
    param_str = ", ".join(f"{k} := {v}" for k, v in params.items())
    lean_expr = expression_to_lean(expression, params)
    return f"""\
/-- Gate PASS: {gate_name}
    Expression: {expression}
    Parameters: {param_str}
    Max residual: {max_residual:.6f} < threshold {threshold}
    Grid: {grid_name}
    Certification: native_decide on Float bounds --/
def check_{gate_name}_pass : Bool :=
  {grid_name}.all fun (n, v) =>
    (Float.abs (({lean_expr}) - v)) < {threshold}

#eval check_{gate_name}_pass  -- should print true

"""


def emit_gate_failure_exclusion(
    gate_name: str,
    threshold: float,
    expression: str,
    params: dict[str, float],
    grid_name: str,
    max_residual: float,
    worst_point: tuple[float, float] | None = None,
) -> str:
    param_str = ", ".join(f"{k} := {v}" for k, v in params.items())
    lean_expr = expression_to_lean(expression, params)
    return f"""\
/-- Gate FAILURE (exclusion): {gate_name}
    Expression: {expression}
    Parameters: {param_str}
    Max residual: {max_residual:.6f} >= threshold {threshold}
    Grid: {grid_name}
    Certification: native_decide on Float bounds --/
def check_{gate_name}_excluded : Bool :=
  {grid_name}.any fun (n, v) =>
    (Float.abs (({lean_expr}) - v)) >= {threshold}

#eval check_{gate_name}_excluded  -- should print true

"""


def _try_identify_constant(value: float, tol: float = 0.05) -> str | None:
    """Map a fitted float to an exact mathematical constant.

    Uses a curated library of common constants (pi, sqrt, log combinations)
    plus mpmath.identify as a fallback. The tolerance is generous (5%) because
    fitted values on finite data diverge from theoretical constants by O(1/sqrt(n))
    correction terms.

    Returns a string like 'pi*sqrt(2/3)' or None if no match found within tolerance.
    """
    import math as _m

    # Curated constant library: (name, value) pairs
    _CONSTANTS = [
        ("pi", _m.pi),
        ("pi/2", _m.pi / 2),
        ("pi/3", _m.pi / 3),
        ("pi/4", _m.pi / 4),
        ("pi/6", _m.pi / 6),
        ("2*pi", 2 * _m.pi),
        ("sqrt(2)", _m.sqrt(2)),
        ("sqrt(3)", _m.sqrt(3)),
        ("sqrt(5)", _m.sqrt(5)),
        ("sqrt(6)", _m.sqrt(6)),
        ("pi*sqrt(2/3)", _m.pi * _m.sqrt(2 / 3)),
        ("pi*sqrt(1/3)", _m.pi * _m.sqrt(1 / 3)),
        ("pi*sqrt(2)", _m.pi * _m.sqrt(2)),
        ("pi/sqrt(6)", _m.pi / _m.sqrt(6)),
        ("ln(2)", _m.log(2)),
        ("ln(3)", _m.log(3)),
        ("ln(10)", _m.log(10)),
        ("1/ln(2)", 1 / _m.log(2)),
        ("e", _m.e),
        ("1/e", 1 / _m.e),
        ("euler_gamma", 0.5772156649),
    ]

    # Also try simple rationals and negatives
    abs_val = abs(value)
    sign = "-" if value < 0 else ""

    # Check curated constants
    best_match = None
    best_rel_err = tol
    for name, const_val in _CONSTANTS:
        rel_err = abs(abs_val - const_val) / max(const_val, 1e-10)
        if rel_err < best_rel_err:
            best_rel_err = rel_err
            best_match = f"{sign}{name}"

    # Check simple integers
    nearest_int = round(value)
    if nearest_int != 0 and abs(value - nearest_int) / abs(nearest_int) < tol:
        int_err = abs(value - nearest_int) / abs(nearest_int)
        if int_err < best_rel_err:
            best_match = str(nearest_int)

    if best_match:
        return best_match

    # Fallback: mpmath.identify
    try:
        import mpmath
        result = mpmath.identify(value, tol=tol)
        if result:
            return str(result)
    except ImportError:
        pass
    except Exception:
        pass

    return None


def emit_pslq_conjecture(
    expression: str,
    params: dict[str, float],
) -> str:
    """Attempt to map fitted parameters to exact mathematical constants.

    Returns a Lean comment block with the conjecture, or empty string if
    no constants are identified.
    """
    identified: list[tuple[str, float, str]] = []
    for name, value in params.items():
        exact = _try_identify_constant(value)
        if exact:
            identified.append((name, value, exact))

    if not identified:
        return ""

    lines = ["/-- PSLQ Conjecture: Empirical constants mapped to exact expressions"]
    for name, value, exact in identified:
        lines.append(f"    {name} = {value} ≈ {exact}")
    lines.append("")
    lines.append("    This is a CONJECTURE, not a proof. The numerical bounds above")
    lines.append("    are sorry-free (certified by evaluation). The exact-constant")
    lines.append("    identification is a hypothesis generated by PSLQ integer")
    lines.append("    relation algorithm. The epistemic boundary is explicit. --/")
    lines.append("")

    for name, value, exact in identified:
        safe_name = name.replace(".", "_")
        lines.append(f"-- axiom pslq_{safe_name} : {name} = {exact}  -- CONJECTURE (sorry)")
    lines.append("")

    return "\n".join(lines) + "\n"


def emit_exponent_grid_lemma(
    param_name: str,
    free_value: float,
    grid_value: float,
    free_bic: float,
    grid_bic: float,
) -> str:
    return f"""\
/-- Exponent grid: BIC prefers {param_name}={grid_value} over {param_name}={free_value}
    BIC(grid) = {grid_bic:.1f} < BIC(free) = {free_bic:.1f} --/
theorem exponent_grid_{param_name}_{str(grid_value).replace('.','_')} :
  bic_score (d := {grid_value}) < bic_score (d := {free_value}) := by
  -- Numerical: {grid_bic:.1f} < {free_bic:.1f}
  sorry

"""


def emit_topology_exhaustion(
    topology_class: str,
    n_iterations: int,
    all_failed: bool,
) -> str:
    if not all_failed:
        return ""
    return f"""\
/-- Topology class exhaustion: {topology_class}
    {n_iterations} iterations attempted, all failed farther-tail gate.
    No form in this class generalizes beyond the visible window. --/
theorem {topology_class}_class_exhausted :
  ∀ f ∈ topology_class_{topology_class},
    ∃ (n v) ∈ farther_tail_grid,
      |f n - v| ≥ farther_tail_threshold := by
  -- Induction over {n_iterations} iteration witnesses
  sorry

"""


# ---------------------------------------------------------------------------
# Expression translation (Python math → Lean syntax)
# ---------------------------------------------------------------------------

def expression_to_lean(expr: str, params: dict[str, float]) -> str:
    """Best-effort translation of Python math expression to Lean-ish syntax.

    This is approximate — produces readable pseudocode, not valid Lean.
    The actual Lean definitions would use Real.sqrt, Real.log, etc.
    """
    lean = expr
    lean = lean.replace("math.sqrt", "Real.sqrt")
    lean = lean.replace("math.log", "Real.log")
    lean = lean.replace("math.exp", "Real.exp")
    lean = lean.replace("math.pi", "Real.pi")
    lean = lean.replace("math.e", "Real.exp 1")
    lean = lean.replace("**", "^")
    # Substitute parameter values
    for name, val in params.items():
        lean = lean.replace(name, f"({val})")
    return lean



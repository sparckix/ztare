def compile_project(project_dir: Path, strict: bool = False) -> str:
    """Read all ZTARE artifacts and generate Lean 4 proof stubs.

    GP-135: `strict=True` enables the P4 gate preamble (warningAsError,
    axiom allowlist banner). Post-compile verification lives in
    `scripts/verify_lean_stub.py`.
    """
    project_name = project_dir.name
    output_parts: list[str] = [emit_preamble(project_name, strict=strict)]

    # Load evidence grids
    for name, filename in [
        ("visible_grid", "evidence.txt"),
        ("holdout_grid", "evidence_holdout.txt"),
        ("farther_tail_grid", "evidence_farther_tail.txt"),
    ]:
        path = project_dir / filename
        if path.exists():
            pts = load_evidence(path)
            output_parts.append(emit_evidence_def(name, pts))

    # Load gate harness results: run gate_harness.py directly if available,
    # fall back to champion/latest eval files.
    gate_results = None
    gate_harness_path = project_dir / "gate_harness.py"
    if gate_harness_path.exists():
        import subprocess
        try:
            proc = subprocess.run(
                [sys.executable, str(gate_harness_path), "--emit-deterministic-gates"],
                capture_output=True, text=True, timeout=30,
            )
            if proc.returncode == 0 and proc.stdout.strip():
                gate_results = json.loads(proc.stdout)
        except Exception:
            pass
    if gate_results is None:
        for fname in ["champion_eval_results.json", "latest_eval_results.json"]:
            path = project_dir / fname
            if path.exists():
                try:
                    gate_results = json.loads(path.read_text(encoding="utf-8"))
                    break
                except Exception:
                    continue

    # Load fit results from workspace
    workspace = project_dir / "workspace"
    fit_results: list[dict] = []
    if workspace.exists():
        for fit_path in sorted(workspace.glob("fit_result_iter_*.json")):
            try:
                fit_results.append(json.loads(fit_path.read_text(encoding="utf-8")))
            except Exception:
                continue

    # Emit gate pass/failure lemmas from gate harness
    if gate_results and gate_results.get("gates"):
        raw_gates = gate_results["gates"]
        # Normalize: handle both dict-of-dicts and list-of-dicts formats
        if isinstance(raw_gates, list):
            gate_items = [(g.get("name", f"gate_{i}"), g) for i, g in enumerate(raw_gates)]
        else:
            gate_items = list(raw_gates.items())
        for gate_name, gate_data in gate_items:
            threshold = gate_data.get("threshold", 0.05)
            value = gate_data.get("value", gate_data.get("actual", float("inf")))
            passed = gate_data.get("pass", gate_data.get("passed", False))

            # Determine which grid this gate operates on
            grid_name = "holdout_grid"
            if "farther_tail" in gate_name:
                grid_name = "farther_tail_grid"

            # Get expression and params from latest fit
            expression = "f n"
            params: dict[str, float] = {}
            if fit_results:
                latest = fit_results[-1]
                expression = latest.get("expression", "f n")
                params = latest.get("fitted_params", {})

            if passed:
                output_parts.append(emit_gate_pass_witness(
                    gate_name=gate_name,
                    threshold=threshold,
                    expression=expression,
                    params=params,
                    grid_name=grid_name,
                    max_residual=value,
                ))
            else:
                output_parts.append(emit_gate_failure_exclusion(
                    gate_name=gate_name,
                    threshold=threshold,
                    expression=expression,
                    params=params,
                    grid_name=grid_name,
                    max_residual=value,
                ))

    # Emit per-iteration exclusion lemmas for failed fits
    for idx, fit in enumerate(fit_results):
        if fit.get("status") != "success":
            continue
        expr = fit.get("expression", "")
        fp = fit.get("fitted_params", {})
        max_res = fit.get("max_abs_residual", 999)
        # If the iteration was reverted (score 0), it's an exclusion
        output_parts.append(f"""\
/-- Iteration {idx + 1} candidate: {expr[:60]}
    Visible max_res: {max_res:.6f}
    Status: reverted (failed holdout or score not improved) --/
-- exclusion witness available in fit_result_iter_{idx + 1:03d}.json

""")

    # PSLQ conjecture: attempt to map champion's fitted params to exact constants
    if fit_results:
        last_success = [f for f in fit_results if f.get("status") == "success"]
        if last_success:
            latest = last_success[-1]
            fp = latest.get("fitted_params", {})
            if fp:
                pslq = emit_pslq_conjecture(
                    latest.get("expression", ""),
                    fp,
                )
                if pslq:
                    output_parts.append(pslq)

    # Emit topology class summary
    topology_counts: dict[str, int] = {}
    for fit in fit_results:
        if fit.get("status") != "success":
            continue
        expr = fit.get("expression", "").lower()
        if "**" in expr and "math.log" not in expr.split("**")[0][-10:]:
            cls = "power_law"
        elif "math.exp" in expr:
            cls = "exponential"
        elif "math.log" in expr:
            cls = "log_polynomial"
        else:
            cls = "other"
        topology_counts[cls] = topology_counts.get(cls, 0) + 1

    for cls, count in topology_counts.items():
        output_parts.append(emit_topology_exhaustion(
            topology_class=cls,
            n_iterations=count,
            all_failed=True,  # all iterations in GP-088 were reverted
        ))

    return "\n".join(output_parts)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Compile ZTARE gate results into Lean 4 proof stubs."
    )
    parser.add_argument("--project", required=True, help="Project name")
    parser.add_argument("--output", default=None, help="Output .lean file path")
    parser.add_argument(
        "--strict",
        action="store_true",
        help=(
            "GP-135 P4-gate hardening: emit stubs with warningAsError so "
            "unclosed `sorry` is a compile error. Use with "
            "`scripts/verify_lean_stub.py` for axiom allowlist enforcement."
        ),
    )
    args = parser.parse_args()

    project_dir = PROJECTS_DIR / args.project
    if not project_dir.exists():
        print(f"ERROR: {project_dir} does not exist", file=sys.stderr)
        return 1

    lean_code = compile_project(project_dir, strict=args.strict)

    if args.output:
        out_path = Path(args.output)
    else:
        out_path = project_dir / f"{args.project}.lean"

    out_path.write_text(lean_code, encoding="utf-8")
    print(f"Lean 4 proof stubs written to: {out_path}")
    print(f"  Gate lemmas: {lean_code.count('theorem ')}")
    print(f"  Evidence grids: {lean_code.count('def ') - 1}")  # minus preamble
    return 0


if __name__ == "__main__":
    sys.exit(main())

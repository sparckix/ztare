import importlib.util
import sys
from pathlib import Path


DECL_INDEX_PATH = Path(__file__).resolve().parents[2] / "scripts" / "lean_decl_index.py"
CLOSED_LOOP_PATH = Path(__file__).resolve().parents[2] / "scripts" / "llm_theorem_closed_loop.py"
LEAN_GATE_PATH = Path(__file__).resolve().parents[2] / "src" / "ztare" / "gates" / "lean_proof_gate.py"


def _load(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def test_decl_index_includes_structure_fields_and_local_binders(tmp_path):
    mod = _load(DECL_INDEX_PATH, "lean_decl_index_test_fields")
    lean_dir = tmp_path / "ZtareProofs"
    lean_dir.mkdir()
    (lean_dir / "sample.lean").write_text(
        "structure LeraySelfTaxProfilePriceStream where\n"
        "  payoffLimit : Real\n\n"
        "def leraySelfTaxLimitPrice (_S : LeraySelfTaxProfilePriceStream) : Real := 0\n",
        encoding="utf-8",
    )

    idx = mod.build_index(lean_dir)
    result = mod.check_nomination(
        "theorem candidate_name (S : LeraySelfTaxProfilePriceStream) : "
        "S.payoffLimit ≤ leraySelfTaxLimitPrice S := by\n"
        "  exact le_rfl",
        idx,
    )

    assert result["valid"] is True
    assert "candidate_name" not in result["unresolved"]
    assert "S.payoffLimit" not in result["unresolved"]
    assert "le_rfl" not in result["unresolved"]



    proofs_root = tmp_path / "ztare_proofs"
    target_dir = proofs_root / "ZtareProofs"
    target_dir.mkdir(parents=True)
    lean_path = target_dir / "non_theorem.lean"
    lean_path.write_text("def helperOnly : True := True.intro\n", encoding="utf-8")

    audit = mod.audit_axioms(lean_path, proofs_root)

    assert audit["axiom_audit_passed"] is False
    assert "<no-theorem-or-lemma-declarations>" in audit["extra_axioms"]

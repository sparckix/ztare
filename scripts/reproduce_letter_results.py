def spectral_slope(residuals):
    freqs, psd = welch(residuals, nperseg=min(4096, len(residuals) // 4))
    mask = (freqs > 0) & (psd > 0)
    if mask.sum() < 5: return None, None
    sl, _, rv, _, _ = linregress(np.log10(freqs[mask]), np.log10(psd[mask]))
    return round(float(sl), 3), round(float(rv**2), 3)

def hurst_dfa(x):
    scales = np.unique(np.logspace(1, np.log10(len(x) // 4), 20).astype(int))
    flucts = []
    for s in scales:
        ns = len(x) // s
        if ns < 2: continue
        segs = x[:ns * s].reshape(ns, s)
        t = np.arange(s)
        f = [np.sqrt(np.mean((seg - np.polyval(np.polyfit(t, seg, 1), t))**2)) for seg in segs]
        flucts.append((s, np.mean(f)))
    if len(flucts) < 5: return None
    ss, ff = zip(*flucts)
    H, _, _, _, _ = linregress(np.log(ss), np.log(ff))
    return round(float(H), 4)


def sieve_primes(limit):
    is_prime = bytearray([1]) * (limit + 1)
    is_prime[0] = is_prime[1] = 0
    for i in range(2, int(limit**0.5) + 1):
        if is_prime[i]:
            is_prime[i*i::i] = bytearray(len(is_prime[i*i::i]))
    return [i for i in range(limit + 1) if is_prime[i]]

primes = sieve_primes(8_000_000)

def wolf_spectrum(seq, L, max_val):
    n_int = max_val // L
    if n_int < 64: return None, None
    counts = np.zeros(n_int)
    j = 0
    for i in range(n_int):
        lo, hi = i * L, (i + 1) * L
        while j < len(seq) and seq[j] < lo: j += 1
        while j < len(seq) and seq[j] < hi:
            counts[i] += 1; j += 1
    counts -= np.mean(counts)
    freqs, psd = welch(counts, nperseg=min(256, len(counts) // 2))
    mask = (freqs > 0) & (psd > 0)
    if mask.sum() < 5: return None, None
    sl, _, rv, _, _ = linregress(np.log10(freqs[mask]), np.log10(psd[mask]))
    return round(float(sl), 3), round(float(rv**2), 3)


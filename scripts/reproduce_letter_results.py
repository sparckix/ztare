        H = hurst_dfa(resid)
        entry = {"sequence": label, "method": f"MA-{W}", "slope": sl, "r2": r2, "H": H}
        detrend_table.append(entry)
        print(f"  {label:>6s} MA-{W:>3d}: slope={sl}, H={H}")


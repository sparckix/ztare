        H = hurst_dfa(resid)
        entry = {"sequence": label, "method": f"poly-{deg}", "slope": sl, "r2": r2, "H": H}
        detrend_table.append(entry)
        print(f"  {label:>6s} poly-{deg}: slope={sl}, H={H}")

